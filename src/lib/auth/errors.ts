export type AuthErrorCode = "INVALID_CREDENTIALS" | "ACCOUNT_DISABLED" | "DUPLICATE_EMAIL" |
  "INVALID_RECOVERY_LINK" | "EXPIRED_RECOVERY_LINK" | "USED_RECOVERY_LINK" | "RATE_LIMITED" |
  "UNAVAILABLE" | "EMAIL_NOT_VERIFIED" | "EMAIL_VERIFICATION_REQUIRED" | "TERMS_ACCEPTANCE_REQUIRED" |
  "PASSWORD_RESET_REQUIRED" | "AUTHENTICATION_REQUIRED" | "VALIDATION_ERROR" | "LOGOUT_UNCERTAIN" |
  "REQUEST_UNCERTAIN" | "INVALID_RESPONSE" | "EMAIL_ALREADY_REGISTERED" | "ACCOUNT_CREATED_EMAIL_FAILED" | "TERMS_VERSION_OUTDATED" |
  "CURRENT_PASSWORD_INCORRECT" | "LINK_INVALID_OR_EXPIRED" | "PASSWORD_REUSE";

export class AuthClientError extends Error {
  constructor(public code: AuthErrorCode, public retryAfter?: number, public fieldErrors: Record<string, string> = {}) {
    super(code); this.name = "AuthClientError";
  }
}
